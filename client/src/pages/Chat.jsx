function AIOfflineBanner({ content }) {
  // Parse metrics out of the notice string for a cleaner display
  const rowsMatch   = content.match(/Found (\d+) results/);
  const colsMatch   = content.match(/(\d+) columns/);
  const rows  = rowsMatch?.[1];
  const cols  = colsMatch?.[1];

  return (
    <div style={{
      display: 'flex', alignItems: 'flex-start', gap: '0.65rem',
      padding: '0.75rem 1rem', borderRadius: '10px',
      background: 'rgba(249,116,75,0.08)', border: '1px solid rgba(249,116,75,0.25)',
      fontSize: '0.83rem', color: 'var(--navy)',
      margin: '0.3rem 0',
    }}>
      <AlertTriangle size={15} strokeWidth={2} color="var(--orange)" style={{ marginTop: 2, flexShrink: 0 }} />
      <div>
        <div style={{ fontWeight: 600, color: 'var(--orange)', marginBottom: '0.2rem' }}>
          AI engine is offline — using basic query mode
        </div>
        <div style={{ color: 'var(--text-secondary)', lineHeight: 1.5 }}>
          Ollama (local AI) is not running. Results are generated by rule-based SQL only.
          {rows && cols && (
            <span style={{ marginLeft: 6, color: 'var(--teal)', fontWeight: 600 }}>
              Found {rows} rows · {cols} columns.
            </span>
          )}
        </div>
      </div>
    </div>
  );
}

