/* ── Helpers ── */

// Returns true if the SQL is a real query worth showing, not an internal fallback
function isRealSQL(sql) {
  if (!sql) return false;
  const s = sql.trim().toUpperCase();
  // Hide internal no-schema / no-connection fallback queries
  if (s.includes("'NO DATABASE SCHEMA AVAILABLE'")) return false;
  if (s.includes("'NO DATABASE CONNECTION")) return false;
  if (s.includes('AS MESSAGE') && s.startsWith("SELECT '")) return false;
  return true;
}

// Extract a clean, friendly error string from raw error messages
function friendlyError(content) {
  if (!content) return null;
  const c = content.toString();
  if (c.includes('No database connection in context') || c.includes('No database schema')) {
    return {
      title: 'No database selected',
      detail: 'Please select a connection from the dropdown above before asking a question.',
      icon: Database,
      type: 'warn',
    };
  }
  if (c.toLowerCase().includes('network') || c.toLowerCase().includes('fetch')) {
    return {
      title: 'Connection problem',
      detail: 'Could not reach the server. Check that the backend and agent services are running.',
      icon: WifiOff,
      type: 'error',
    };
  }
  if (c.toLowerCase().startsWith('error:') || c.toLowerCase().includes('failed')) {
    return {
      title: 'Something went wrong',
      detail: c.replace(/^error:\s*/i, ''),
      icon: XCircle,
      type: 'error',
    };
  }
  return null;
}

